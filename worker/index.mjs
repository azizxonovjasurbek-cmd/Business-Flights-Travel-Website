// Cloudflare Worker entry (wrangler.jsonc `main`).
//
// Serves prerendered pages, their React Server Component (RSC) payloads and the
// prefetch segments straight from static assets, WITHOUT loading or running the
// Next.js server. Everything else (forms / server actions, `/flights`, redirects,
// unknown URLs, any request this file is not certain about) is delegated, with
// the original request, to the regular OpenNext worker in .open-next/worker.js.
//
// Why: on the Workers Free plan a request may use ~10 ms CPU; running Next for a
// prerendered page exceeded that in production (Error 1102). The files served
// here are generated by `next build` itself and published by scripts/cf-build.mjs.
//
// Kill switch: set the Worker variable DISABLE_PRERENDER_FASTPATH=1 in the
// Cloudflare dashboard to send every request through OpenNext again, no redeploy.

import { buildSecurityHeaders } from "../src/lib/security-headers.ts";
import manifest from "./prerender-manifest.json";

const PREFIX = "/cdn-cgi/_prerendered";
const SECURITY_HEADERS = buildSecurityHeaders(false);
const PAGES = new Set(manifest.pages);
const BODIES = manifest.bodies;

// Same values the Next/OpenNext path sends for prerendered responses.
const CACHE_CONTROL = "s-maxage=31536000";
const VARY = "rsc, next-router-state-tree, next-router-prefetch, next-router-segment-prefetch";

// Segment names come from a request header: allow only what Next generates.
const SAFE_SEGMENT = /^\/[A-Za-z0-9_$\-./]+$/;

let nextWorker;
function delegate(request, env, ctx) {
  // Imported lazily so requests served here never evaluate the large Next bundle.
  nextWorker ??= import("../.open-next/worker.js");
  return nextWorker.then((mod) => mod.default.fetch(request, env, ctx));
}

async function readAsset(env, assetPath) {
  const response = await env.ASSETS.fetch(`http://assets.local${assetPath}`);
  if (!response.ok) {
    await response.body?.cancel();
    return null;
  }
  return response;
}

function respond(request, asset, headers) {
  for (const { key, value } of SECURITY_HEADERS) headers.set(key, value);
  headers.set("x-bft-prerendered", "1");
  return new Response(request.method === "HEAD" ? null : asset.body, { status: 200, headers });
}

export default {
  async fetch(request, env, ctx) {
    if (env.DISABLE_PRERENDER_FASTPATH === "1" || (request.method !== "GET" && request.method !== "HEAD")) {
      return delegate(request, env, ctx);
    }

    const url = new URL(request.url);
    const route = url.pathname;
    const isRsc = request.headers.get("rsc") === "1";
    const hasRscParam = url.searchParams.has("_rsc");

    try {
      if (!isRsc && !hasRscParam) {
        if (PAGES.has(route)) {
          const asset = await readAsset(env, `${PREFIX}${route === "/" ? "/index" : route}.page`);
          if (asset) {
            return respond(
              request,
              asset,
              new Headers({
                "content-type": "text/html; charset=utf-8",
                "cache-control": CACHE_CONTROL,
                vary: VARY,
                "x-nextjs-prerender": "1",
                "x-nextjs-stale-time": "300",
              }),
            );
          }
        } else if (Object.hasOwn(BODIES, route)) {
          const [contentType, cacheControl] = BODIES[route];
          const asset = await readAsset(env, `${PREFIX}${route}.body`);
          if (asset) return respond(request, asset, new Headers({ "content-type": contentType, "cache-control": cacheControl, vary: VARY }));
        }
      } else if (isRsc && hasRscParam && PAGES.has(route)) {
        // Segment prefetch: the request Next's client sends for <Link> prefetching.
        const segment = request.headers.get("next-router-segment-prefetch");
        if (segment && SAFE_SEGMENT.test(segment) && !segment.includes("..") && !segment.includes("//")) {
          const base = route === "/" ? "/index" : route;
          const asset = await readAsset(env, `${PREFIX}${base}.segments${segment}.segment.rsc`);
          if (asset) {
            return respond(
              request,
              asset,
              new Headers({
                "content-type": "text/x-component",
                "cache-control": CACHE_CONTROL,
                vary: VARY,
                "x-nextjs-prerender": "1",
                "x-nextjs-postponed": "2",
              }),
            );
          }
        }
      }
    } catch (error) {
      // Never fail a request because of the fast path: fall back to OpenNext.
      console.error("[prerender-fastpath] falling back to OpenNext:", error);
    }

    return delegate(request, env, ctx);
  },
};
