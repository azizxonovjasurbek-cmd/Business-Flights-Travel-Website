export function searchAirports(query: string, limit: number = 8): Airport[] {
  const q = query.trim().toUpperCase();
  if (!q) return [];

  const scored: Array<{ airport: Airport; score: number }> = [];

  for (const airport of AIRPORTS) {
    const iataU = airport.iata.toUpperCase();
    const cityU = airport.city.toUpperCase();
    const nameU = airport.name.toUpperCase();
    const countryU = airport.country.toUpperCase();

    let score = 0;
    if (iataU === q) score = 100;
    else if (iataU.startsWith(q)) score = 90;
    else if (cityU === q) score = 80;
    else if (cityU.startsWith(q)) score = 70;
    else if (nameU.startsWith(q)) score = 60;
    else if (cityU.includes(q)) score = 40;
    else if (nameU.includes(q)) score = 30;
    else if (countryU.startsWith(q)) score = 20;
    else if (countryU.includes(q)) score = 10;
    else if (iataU.includes(q)) score = 5;

    if (score > 0) scored.push({ airport, score });
  }

  scored.sort((a, b) => b.score - a.score);
  return scored.slice(0, limit).map((s) => s.airport);
}

export function findAirport(iata: string): Airport | undefined {
  const target = iata.trim().toUpperCase();
  return AIRPORTS.find((a) => a.iata.toUpperCase() === target);
}

export function formatAirport(airport: Airport): string {
  return `${airport.iata} – ${airport.city}, ${airport.country} (${airport.name})`;
}
